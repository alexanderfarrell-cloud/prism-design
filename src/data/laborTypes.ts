export const LABOR_TYPES = LABOR_CATEGORIES.flatMap((cat) =>
  cat.laborTypes.map((lt) => ({
    id: lt.id,
    label: lt.name,
    rate: `$${lt.payRate.toFixed(2)}/hr`,
  }))
);

export function getCategoryById(id: string): LaborCategory | undefined {
  return LABOR_CATEGORIES.find((c) => c.id === id);
}

export function getLaborTypeById(
  categoryId: string,
  laborTypeId: string
): LaborType | undefined {
  const category = getCategoryById(categoryId);
  return category?.laborTypes.find((lt) => lt.id === laborTypeId);
}

export function formatCurrency(amount: number): string {
  return `$${amount.toFixed(2)}`;
}

export function getBurdenedRate(lt: LaborType): number {
  return burdenedRate(lt.payRate, lt.burdenPercent);
}

export interface LaborTypeAssignment {
  laborTypeId: string;
  isDefault: boolean;
}

export function getDefaultLaborType(
  assignments: LaborTypeAssignment[]
): LaborType | undefined {
  const defaultAssignment = assignments.find((a) => a.isDefault);
  if (!defaultAssignment) return undefined;
  for (const cat of LABOR_CATEGORIES) {
    const lt = cat.laborTypes.find((t) => t.id === defaultAssignment.laborTypeId);
    if (lt) return lt;
  }
  return undefined;
}
